def table_html(t, C):
    head = "".join(f'<th scope="col">{escape(h)}</th>' for h in t["head"])
    rows = "".join("<tr>" + "".join((f'<th scope="row">{C.html(c)}</th>' if i == 0 else f"<td>{C.html(c)}</td>") for i, c in enumerate(r)) + "</tr>" for r in t["rows"])
    cap = f'<p class="cite">{C.html(t["note"])}</p>' if t.get("note") else ""
    return f'<h3>{escape(t["title"])}</h3><div class="mn-table-wrap"><table class="mn-gen"><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>{cap}'


def gen_table(v):
    """The lithography generations table, computed so λ / 2NA is never typed by hand."""
    g = v["generations"]
    return {"title": "How each generation of light sets the smallest pitch", "head": ["Light", "λ", "NA", "λ / 2NA"],
            "rows": [[x["name"], f'{x["lam"]:g} nm', f'{x["NA"]:.2f}', f'{x["lam"] / (2 * x["NA"]):.1f} nm'] for x in g],
            "note": "Wavelength and NA as in the Physics Lab presets " + " ".join(f"[@{k}]" for k in v["generations_ref"]) + ". λ / 2NA is the single-exposure limit at k₁ = 0.25."}


def variant_html(v, C):
    facts = "".join(f'<li>{C.html(f["t"])}{C.sup(refs_of(f))}</li>' for f in v["facts"])
    pic = f'<figure class="mn-pic mn-euv">{DIAGRAMS[v["diagram"]]()}</figure>' if v.get("diagram") else ""
    safety = f'<p class="mn-safety"><b>Institution-only</b> {C.html(v["safety"])}</p>' if v.get("safety") else ""
    tables = ([gen_table(v)] if v.get("generations") else []) + v.get("tables", [])
    grid = f'<div class="mn-variant-grid">{pic}<div><ul class="mn-facts">{facts}</ul>{safety}</div></div>' if pic else f'<ul class="mn-facts mn-facts-wide">{facts}</ul>{safety}'
    return f'''
<section class="mn-variant" aria-labelledby="variant-h">
  <div class="wrap">
    <p class="eyebrow">{escape(v.get('eyebrow', 'Variant'))}</p>
    <h2 id="variant-h">{escape(v['title'])}</h2>
    <p class="mn-lead">{C.html(v['lead'])}</p>
    {grid}
    {''.join(table_html(t, C) for t in tables)}
  </div>
</section>'''


def photos_html(m, cands):
    out = []
    for cid in m.get("photos", []):
        c = cands[cid]
        ok = c.get("status") == "verified"
        f = c["file"].replace(" ", "_")
        img = (f'<img src="https://commons.wikimedia.org/wiki/Special:FilePath/{escape(f)}?width=640" alt="{escape(c["subject"])}" loading="lazy">'
               if ok else '<div class="mn-ph" aria-hidden="true"><span>photo held until its licence is checked</span></div>')
        credit = f'{escape(c.get("author") or "")} · {escape(c.get("license") or "")}' if ok else "run scripts/check_photo_licenses.py"
        out.append(f'<figure class="mn-photo{" ok" if ok else ""}">{img}<figcaption><b>{escape(c["subject"])}</b>'
                   f'<span>{"Licence verified" if ok else "Licence not yet verified"} · {credit}</span><a href="{COMMONS}{escape(f)}">Wikimedia Commons file page</a></figcaption></figure>')
    return "".join(out)


