def shade(hex_, f):
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    if f >= 0:
        r, g, b = (round(c + (255 - c) * f) for c in (r, g, b))
    else:
        r, g, b = (round(c * (1 + f)) for c in (r, g, b))
    return f"#{r:02x}{g:02x}{b:02x}"


def pts(*p):
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in p)


def box(x0, x1, yb, yt, col, new=False, outline_only=False, glow=False, alpha=1.0):
    """Front, top and right faces of one block. x in px, y screen (yt < yb)."""
    top = pts((x0, yt), (x1, yt), (x1 + OX, yt + OY), (x0 + OX, yt + OY))
    front = pts((x0, yb), (x1, yb), (x1, yt), (x0, yt))
    side = pts((x1, yt), (x1 + OX, yt + OY), (x1 + OX, yb + OY), (x1, yb))
    if outline_only:
        s = 'fill="none" stroke="#f2b84b" stroke-width="1.6" stroke-dasharray="4 3"'
        return f'<polygon points="{top}" {s}/><polygon points="{front}" {s}/>'
    st = ' stroke="#ffffff" stroke-width="1.6" stroke-linejoin="round"' if new else ' stroke="#0a0d11" stroke-opacity=".35" stroke-width=".6"'
    g = ' filter="url(#glow)"' if glow else ""
    op = f' opacity="{alpha}"' if alpha < 1 else ""
    return (f'<g{g}{op}><polygon points="{side}" fill="{shade(col, -.32)}"{st}/>'
            f'<polygon points="{front}" fill="{col}"{st}/>'
            f'<polygon points="{top}" fill="{shade(col, .22)}"{st}/></g>')


def lab(x, y, text, col=None, anchor=None, bold=False):
    st = []
    if col:
        st.append(f"fill:{col}")
    if bold:
        st.append("font-weight:700")
    s = f' style="{";".join(st)}"' if st else ""
    a = f' text-anchor="{anchor}"' if anchor else ""
    return f'<text x="{x:.1f}" y="{y:.1f}" class="lab"{a}{s}>{escape(text)}</text>'


def wrap(text, n=12):
    """Split a tag into lines of at most n characters (the tag column is narrow)."""
    lines = [""]
    for w in text.split():
        if lines[-1] and len(lines[-1]) + 1 + len(w) > n:
            lines.append(w)
        else:
            lines[-1] = (lines[-1] + " " + w).strip()
    return lines


