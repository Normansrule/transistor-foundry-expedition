class Cites:
    """Numbers [@key] in order of first use on one page."""

    def __init__(self, refs):
        self.refs, self.order = refs, []

    def n(self, key):
        if key not in self.refs:
            raise KeyError(f"unknown reference [@{key}]")
        if key not in self.order:
            self.order.append(key)
        return self.order.index(key) + 1

    def sup(self, keys):
        return "<sup>" + ",".join(f'<a href="#ref-{k}">{self.n(k)}</a>' for k in keys) + "</sup>"

    def html(self, text):
        t = escape(text)
        t = re.sub(r"(?:\s*\[@[\w-]+\])+", lambda m: self.sup(re.findall(r"\[@([\w-]+)\]", m.group(0))), t)
        return t

    def md(self, text):
        return re.sub(r"(?:\s*\[@[\w-]+\])+", lambda m: "<sup>" + ",".join(f"[{self.n(k)}](#sources)" for k in re.findall(r"\[@([\w-]+)\]", m.group(0))) + "</sup>", text)


def strip_cites(text):
    return re.sub(r"\s*\[@[\w-]+\]", "", text)


def ref_url(r):
    return f"https://doi.org/{r['doi']}" if r.get("doi") else r.get("url", "")


def refs_of(f):
    return f["refs"] if "refs" in f else [f["ref"]]


