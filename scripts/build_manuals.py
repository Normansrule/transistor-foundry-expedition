def manual_md(m, refs):
    C = Cites(refs)
    slug = m["id"]
    L = [GEN, f"# Manual {m['code']} · {m['title']}", "", f"**{m['subtitle']}.** {C.md(m['intro'])}", "",
         C.md(m["model_after"]), "",
         f"[Open the web manual]({PAGES}/manuals/{slug}.html) (Save as PDF from there) · [All manuals](README.md)", "",
         "> **Read this first.** This manual explains how a cleanroom does each step. It is not a procedure to try at home. "
         "Tier 2 and 3 steps use heat, vacuum and high-voltage equipment or hazardous chemicals that only trained staff may handle.", "",
         "| You need | |", "|---|---|"]
    L += [f"| {n['label']} | ×1{(' · ' + n['from']) if n.get('from') else ''} |" for n in m["you_need"]]
    L.append("")
    for s in m["steps"]:
        L += [f"## {s['n']} · {s['title']}", "",
              f'<img src="img/{slug}_{s["n"]:02d}.svg" width="400" alt="Step {s["n"]}: {escape(s["title"])}">', "",
              f"**Do.** {C.md(s['do'])}", "", *[f"- {C.md(c['t'])}" for c in s["chips"]], "",
              f"**Check.** {C.md(s['check'])}", "",
              "<details><summary>Operation specification · " + TIER[s["tier"]] + "</summary>", "",
              "| | |", "|---|---|", f"| Tool | {s['spec']['tool']} |", f"| Purpose | {s['spec']['purpose']} |"]
        L += [f"| {p['name']} | {p['value']}" + C.md("".join(f" [@{k}]" for k in refs_of(p))) + " |" for p in s["spec"]["params"]]
        L += [f"| Control | {s['spec']['control']} |", f"| Out of control | {C.md(s['spec']['ooc'])} |", "",
              f"**Process engineer.** {C.md(s['deep'])}", "", "</details>", ""]
    v = m.get("variant")
    if v:
        L += [f"## {v['title']}", "", C.md(v["lead"]), ""]
        L += [f"- {C.md(f['t'])}" + C.md("".join(f" [@{k}]" for k in refs_of(f))) for f in v["facts"]]
        if v.get("safety"):
            L += ["", f"> **Institution-only.** {C.md(v['safety'])}"]
        for t in ([gen_table(v)] if v.get("generations") else []) + v.get("tables", []):
            L += ["", f"**{t['title']}**", "", "| " + " | ".join(t["head"]) + " |", "|" + "---|" * len(t["head"])]
            L += ["| " + " | ".join(C.md(c) for c in r) + " |" for r in t["rows"]]
            if t.get("note"):
                L += ["", C.md(t["note"])]
        L.append("")
    L += ["## What the models leave out", ""] + [f"- {C.md(t)}" for t in m["leave_out"]] + [""]
    for k in m["refs"]:
        C.n(k)
    L += ["## Sources", ""] + [f"{i}. [{refs[k]['cite']}]({ref_url(refs[k])}) `{k}`" for i, k in enumerate(C.order, 1)] + [""]
    return "\n".join(L)


def docs_index(doc, manuals):
    L = [GEN, "# Process manuals", "", doc["intro"], "", "| Manual | Steps | Web |", "|---|---|---|"]
    L += [f"| [{m['code']} · {m['title']}]({m['id']}.md) | {len(m['steps'])} | [web]({PAGES}/manuals/{m['id']}.html) |" for m in manuals]
    return "\n".join(L + [""])


def readme_block(doc, manuals):
    L = ["<!-- manuals:start · generated by scripts/build_manuals.py, edit data/manuals.json -->",
         "## Step-by-step process manuals", "",
         "Illustrated manuals in the style of a building-brick instruction book: one picture per step, the new part outlined, "
         "a parts list, and a check at the end of each step. Open any step for the engineer’s operation specification "
         "(tool, cited parameter ranges, control and what to do when it goes wrong). Every web manual has a Save as PDF button.", "",
         "| Manual | Steps | Web | GitHub |", "|---|---|---|---|"]
    for m in manuals:
        s = m["id"]
        L.append(f"| **{m['code']} · {m['title']}** · {m['subtitle']} | {len(m['steps'])} | "
                 f"[web]({PAGES}/manuals/{s}.html) | [read](docs/manuals/{s}.md) |")
    for m in manuals:
        L += ["", f"<details><summary><b>Manual {m['code']} · {m['title']}</b> in {len(m['steps'])} steps</summary>", "", "<table>"]
        steps = m["steps"]
        for i in range(0, len(steps), 2):
            L.append("<tr>")
            for s in steps[i:i + 2]:
                L.append(f'<td width="50%" valign="top"><img src="docs/manuals/img/{m["id"]}_{s["n"]:02d}.svg" alt="Step {s["n"]}: {escape(s["title"])}"><br>'
                         f'<b>{s["n"]} · {escape(s["title"])}</b><br>{escape(strip_cites(s["do"]))}</td>')
            L.append("</tr>")
        L += ["</table>", "", "</details>"]
    L += ["", "Manuals explain how a cleanroom works; they are not home procedures. "
          "Hazardous chemistry, gases, furnaces and high-power lasers are described conceptually only.",
          "<!-- manuals:end -->"]
    return "\n".join(L)


def outputs():
    refs = {r["id"]: r for r in json.loads((DATA / "references.json").read_text(encoding="utf-8"))["references"]}
    cands = {c["id"]: c for c in json.loads((DATA / "photo_candidates.json").read_text(encoding="utf-8"))["candidates"]}
    doc = json.loads((DATA / "manuals.json").read_text(encoding="utf-8"))
    manuals = doc["manuals"]
    out = {}
    for m in manuals:
        out[SITE_OUT / f"{m['id']}.html"] = page_html(m, refs, cands, manuals)
        out[DOCS_OUT / f"{m['id']}.md"] = manual_md(m, refs)
        for s in m["steps"]:
            out[DOCS_OUT / "img" / f"{m['id']}_{s['n']:02d}.svg"] = frame_svg(s, f"Step {s['n']}: {s['title']}. {strip_cites(s['do'])}") + "\n"
    out[DOCS_OUT / "README.md"] = docs_index(doc, manuals)
    shelf = SITE / "manuals.html"
    out[shelf] = shelf_html(doc, manuals, refs, shelf.read_text(encoding="utf-8") if shelf.exists() else None)
    readme = README.read_text(encoding="utf-8")
    block = readme_block(doc, manuals)
    if "<!-- manuals:start" in readme:
        readme = re.sub(r"<!-- manuals:start.*?<!-- manuals:end -->", lambda _: block, readme, flags=re.S)
    else:
        readme = readme.replace("\n## The interactive site", "\n" + block + "\n\n## The interactive site", 1)
    out[README] = readme
    return out


def main(argv):
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("out of date:", *stale, sep="\n  ")
        return 1
    print(f"{'checked' if check else 'wrote'} manuals ({len(stale)} file(s) {'stale' if check else 'changed'})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
