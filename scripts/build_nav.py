"""Write the same main navigation into every page from one definition.

    python scripts/build_nav.py          rewrite the <nav> block in site/*.html
    python scripts/build_nav.py --check  exit 1 if any page is out of date (used by the tests)

Every page gets: the brand, the six pages (always one click away, current page marked with
aria-current), an "On this page" menu with the page's sections, and the Source link. Below
1100 px the page links fold into the same menu, so a phone can reach every page.
"""
from __future__ import annotations

import re
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
NAME = "Transistor Foundry Expedition"
REPO_URL = "https://github.com/Normansrule/transistor-foundry-expedition"

PAGES = [
    ("index", "History"),
    ("devices", "Device Atlas"),
    ("physics", "Physics Lab"),
    ("circuits", "Circuit Lab"),
    ("process", "Process Lab"),
    ("analog", "Analog & RF"),
]

SECTIONS = {
    "index": [("scale", "Scale"), ("timeline", "Timeline"), ("explorer", "3D explorer"), ("fab", "Fab"),
              ("lab", "Device lab"), ("moore", "Moore’s law"), ("chips", "Chips"), ("materials", "Materials"),
              ("diamond", "Diamond"), ("niche", "Niche atlas"), ("frontier", "Frontier"), ("sources", "Sources")],
    "devices": [("primer", "Primer"), ("atlas", "Atlas"), ("gallery", "Gallery"), ("compare", "Compare"),
                ("align", "Materials"), ("hetero", "Heterojunctions"), ("quiz", "Quiz")],
    "physics": [("crystal", "Crystals"), ("kp", "Band gaps"), ("bands", "Carriers"), ("pn", "p–n junction"),
                ("mos", "MOS capacitor"), ("mosfet", "MOSFET"), ("tunnel", "Oxide tunnelling"),
                ("qw", "Quantum well"), ("short", "Short channel"), ("drift", "Velocity limit"),
                ("heat", "Self-heating"), ("litho", "Lithography"), ("inverter", "Inverter"),
                ("ballistic", "Ballistic limit"), ("wires", "Wires"), ("pl-sources", "Sources")],
    "circuits": [("gates", "Logic gates"), ("adder", "Adder"), ("sram", "SRAM"), ("flash", "Flash"),
                 ("cl-sources", "Sources")],
    "process": [("oxide", "Oxidation"), ("implant", "Implant and anneal"), ("yield", "Yield and cost"),
                ("em", "Electromigration"), ("pr-sources", "Sources")],
    "analog": [("amp", "Amplifier"), ("gain", "Gain"), ("bode", "Frequency response"), ("noise", "Noise"),
               ("an-sources", "Sources")],
}

BRAND_SVG = ('<svg viewBox="0 0 24 24" aria-hidden="true"><rect x="2" y="15" width="20" height="6" rx="1.5" fill="#4b596d"/>'
             '<rect x="3" y="13" width="6" height="3" fill="#3f7fe0"/><rect x="15" y="13" width="6" height="3" fill="#3f7fe0"/>'
             '<rect x="9" y="12.2" width="6" height="1.2" fill="#9a80dc"/><rect x="9" y="5" width="6" height="7.2" rx="1" fill="#f2b84b"/></svg>')
GH_SVG = '<svg width="16" height="16" viewBox="0 0 16 16" aria-hidden="true"><path fill="currentColor" d="M8 0C3.58 0 0 3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-.94-.82-1.13-.28-.15-.68-.52-.01-.53.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-.89-3.64-3.95 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27.68 0 1.36.09 2 .27 1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95.29.25.54.73.54 1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.013 8.013 0 0016 8c0-4.42-3.58-8-8-8z"/></svg>'

START = "<!-- nav:start · generated by scripts/build_nav.py, edit there -->"
END = "<!-- nav:end -->"


def page_link(slug: str, label: str, here: str, cls: str = "") -> str:
    cur = ' aria-current="page"' if slug == here else ""
    c = f' class="{cls}"' if cls else ""
    return f'<a{c} href="{slug}.html"{cur}>{escape(label)}</a>'


def render(here: str) -> str:
    pages = "\n".join(f"      {page_link(s, l, here)}" for s, l in PAGES)
    menu_pages = "\n".join(f"          <li>{page_link(s, l, here)}</li>" for s, l in PAGES)
    secs = "\n".join(f'          <li><a href="#{i}">{escape(l)}</a></li>' for i, l in SECTIONS.get(here, []))
    brand_href = "#top" if here == "index" else "index.html"
    return f"""{START}
<nav class="nav" aria-label="Main">
  <div class="wrap">
    <a class="brand" href="{brand_href}" aria-label="{NAME} home">
      {BRAND_SVG}
      <span><span class="brand-lead">Transistor </span>Foundry Expedition</span>
    </a>
    <div class="nav-pages">
{pages}
    </div>
    <details class="nav-menu">
      <summary><span class="nm-wide">On this page</span><span class="nm-narrow">Menu</span></summary>
      <div class="nav-menu-panel">
        <p class="nm-h nm-pages-h">Pages</p>
        <ul class="nm-pages">
{menu_pages}
        </ul>
        <p class="nm-h">On this page</p>
        <ul>
{secs}
        </ul>
      </div>
    </details>
    <a class="nav-gh" href="{REPO_URL}" rel="noopener" aria-label="Source on GitHub">
      {GH_SVG}
      <span>Source</span>
    </a>
  </div>
</nav>
{END}"""


NAV_RE = re.compile(r"(?:<!-- nav:start[^>]*-->\s*)?<nav class=\"nav\".*?</nav>(?:\s*<!-- nav:end -->)?", re.S)


def main(check: bool = False) -> int:
    stale = []
    for slug, _ in PAGES:
        path = SITE / f"{slug}.html"
        html = path.read_text(encoding="utf-8")
        new = NAV_RE.sub(lambda _m: render(slug), html, count=1)
        if 'src="js/nav.js"' not in new:
            new = new.replace("</body>", '<script type="module" src="js/nav.js"></script>\n</body>', 1)
        if new != html:
            stale.append(path.name)
            if not check:
                path.write_text(new, encoding="utf-8")
    if check and stale:
        print("navigation out of date in: " + ", ".join(stale) + "  (run python scripts/build_nav.py)")
        return 1
    if not check:
        print(f"nav: {len(stale)} page(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
