"""Make the site an installable, offline-capable progressive web app (PWA).

    python scripts/build_pwa.py          write site/sw.js, site/manifest.webmanifest and the head tags
    python scripts/build_pwa.py --check  exit 1 if any of them is out of date (used by the tests)

What it writes:
- site/manifest.webmanifest: name, colours, icons and shortcuts to the ten pages.
- site/sw.js: the service worker. Its precache list is every file under site/ (except the large
  social-preview image), and its cache name carries the version from CITATION.cff, so a new release
  replaces the old cache in one step.
- In each top-level page's <head>: the manifest link, theme colour and Apple touch icon, between
  pwa:start / pwa:end markers. The manuals get the same tags from scripts/build_manuals.py.

The service worker itself is registered by site/js/nav.js and site/js/manual.js.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
NAME = "Transistor Foundry Expedition"
SHORT = "Foundry"
THEME = "#0a0d11"
SKIP = {"sw.js", "assets/og.png"}           # the worker itself, and the 300 KB social-preview image
SKIP_SUFFIX = (".map",)
START = "<!-- pwa:start · generated by scripts/build_pwa.py -->"
END = "<!-- pwa:end -->"
SHORTCUTS = [("fab", "Fab Journey"), ("process", "Process Lab"), ("manuals", "Manuals"), ("experiments", "Experiments")]


def version() -> str:
    return re.search(r"^version:\s*([0-9.]+)", (ROOT / "CITATION.cff").read_text(encoding="utf-8"), re.M).group(1)


def head_tags(prefix: str = "") -> str:
    return (f'{START}\n<link rel="manifest" href="{prefix}manifest.webmanifest">\n'
            f'<meta name="theme-color" content="{THEME}">\n'
            f'<link rel="apple-touch-icon" href="{prefix}assets/icons/icon-180.png">\n{END}')


def precache() -> list[str]:
    out = []
    for p in sorted(SITE.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(SITE).as_posix()
        if rel in SKIP or rel.endswith(SKIP_SUFFIX) or rel.startswith(".") or "/." in rel:
            continue
        out.append(rel)
    return ["./"] + out


def manifest() -> str:
    m = {
        "name": NAME,
        "short_name": SHORT,
        "description": "How transistors are made, from sand to a finished chip: process theatres, a Virtual Fab, "
                       "manuals, experiments and a 3D layer builder. Works offline once installed.",
        "id": "./",
        "start_url": "./index.html",
        "scope": "./",
        "display": "standalone",
        "background_color": THEME,
        "theme_color": THEME,
        "lang": "en",
        "categories": ["education", "science"],
        "icons": [
            {"src": "assets/icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
            {"src": "assets/icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
            {"src": "assets/icons/maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
            {"src": "assets/favicon.svg", "sizes": "any", "type": "image/svg+xml", "purpose": "any"},
        ],
        "shortcuts": [{"name": label, "url": f"./{slug}.html"} for slug, label in SHORTCUTS],
    }
    return json.dumps(m, indent=2, ensure_ascii=False) + "\n"


def sw(files: list[str]) -> str:
    # The cache name changes whenever the version or any precached file changes.
    h = hashlib.sha256()
    for rel in files[1:]:
        h.update(rel.encode())
        h.update((SITE / rel).read_bytes())
    tag = f"tfe-v{version()}-{h.hexdigest()[:10]}"
    listing = ",\n".join(f"  {json.dumps(f)}" for f in files)
    return f"""// Service worker · generated by scripts/build_pwa.py, do not edit by hand.
// Precache the whole site on install so every page, lab and manual works offline.
// Same-origin requests: cache first, then network. Photos hotlinked from Wikimedia Commons:
// network first, and the last 80 seen are kept for offline use.
const CACHE = {json.dumps(tag)};
const PHOTOS = 'tfe-photos';
const PHOTO_MAX = 80;
const FILES = [
{listing}
];

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== PHOTOS).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

async function trim(cache) {{
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - PHOTO_MAX; i++) await cache.delete(keys[i]);
}}

self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {{
    e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).catch(() =>
      req.mode === 'navigate' ? caches.match('index.html') : Response.error())));
  }} else if (/(^|\\.)wikimedia\\.org$/.test(url.hostname)) {{
    e.respondWith(fetch(req).then(async (res) => {{
      const c = await caches.open(PHOTOS);
      await c.put(req, res.clone());
      trim(c);
      return res;
    }}).catch(() => caches.match(req).then((hit) => hit || Response.error())));
  }}
}});
"""


def with_head(html: str, prefix: str = "") -> str:
    tags = head_tags(prefix)
    if START in html:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: tags, html, flags=re.S)
    return html.replace("</head>", tags + "\n</head>", 1)


def outputs() -> dict[Path, str]:
    out = {SITE / "manifest.webmanifest": manifest()}
    for page in sorted(SITE.glob("*.html")):
        out[page] = with_head(page.read_text(encoding="utf-8"))
    # sw.js last: it hashes the pages as they will be written.
    return out


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    outs = outputs()
    for path, text in outs.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not check:
            path.write_text(text, encoding="utf-8")
    sw_text = sw(precache())
    swp = SITE / "sw.js"
    if not (swp.exists() and swp.read_text(encoding="utf-8") == sw_text):
        stale.append(swp)
        if not check:
            swp.write_text(sw_text, encoding="utf-8")
    for p in stale:
        print(("stale: " if check else "wrote: ") + p.relative_to(ROOT).as_posix())
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
