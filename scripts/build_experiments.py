"""Write site/experiments.html from data/experiments.json.

    python scripts/build_experiments.py          rewrite the page
    python scripts/build_experiments.py --check  exit 1 if the page is out of date (used by the tests)

The page is static HTML (every experiment, its method, comparisons and sources are readable
without JavaScript); site/js/experiments/main.js adds the CSV fitter to each experiment.
Run scripts/build_nav.py afterwards to fill in the navigation block.
"""
from __future__ import annotations

import json
import re
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "site" / "experiments.html"
NAV = ('<!-- nav:start · generated by scripts/build_nav.py, edit there -->\n<nav class="nav" aria-label="Main"></nav>\n<!-- nav:end -->')

FORMULA = {
    "yield_poisson": "ln Y = −D·A",
    "moore": "log₂ N = a + year / T",
    "sqrt_t": "x² = k (t − t₀)",
    "capacitor": "C = ε_r ε₀ · A/t",
    "grating": "sin θ = m λ / d",
    "diode": "ln I = ln I_s + V / n V_T",
    "led": "V_on = (h c / e) · 1/λ + V₀",
    "mosfet": "√I_D = √K (V_GS − V_t)",
    "tlm": "R = 2R_c + R_s L / W",
    "diode_temp": "V = V₀ + (dV/dT)·T",
    "proximity": "W² = λ_eff · g",
    "crystal": "m = m₀ + rate · day",
    "fourpoint": "R_s = (π / ln 2) · V/I",
    "etch": "removed = rate · (t − t₀)",
}


def sub(text: str) -> str:
    """Escape, then write X_y as X<sub>y</sub> (V_t, R_s, ε_r ...)."""
    return re.sub(r"(?<=[A-Za-zελ₀])_([A-Za-z0-9]+)", r"<sub>\1</sub>", escape(text))


def chips(keys, refs) -> str:
    return '<div class="refchips">' + "".join(
        f'<a href="#ref-{k}" title="{escape(refs[k]["cite"])}">{k}</a>' for k in keys) + "</div>"


def tier_badge(t: int) -> str:
    return f'<span class="xp-tier t{t}">Tier {t}</span>'


def card(x) -> str:
    return (f'    <li class="xp-card" data-tier="{x["tier"]}">\n'
            f'      <a href="#ex-{x["id"]}">\n'
            f'        <span class="xp-card-top"><span class="xp-code">EXPERIMENT {x["n"]:02d}</span>{tier_badge(x["tier"])}</span>\n'
            f'        <b>{escape(x["title"])}</b>\n'
            f'        <span class="xp-card-sub">{escape(x["short"])}</span>\n'
            f'        <span class="xp-card-eq">{sub(FORMULA[x["model"]])}</span>\n'
            f'        <span class="xp-card-time">{escape(x["time"])}</span>\n'
            f'      </a>\n    </li>')


def article(x, refs, tiers) -> str:
    t = x["tier"]
    links = "".join(f'<li><a href="{escape(l["href"])}">{escape(l["label"])} →</a></li>' for l in x["links"])
    need = "".join(f"<li>{sub(n)}</li>" for n in x["need"])
    steps = "".join(f"<li>{sub(s)}</li>" for s in x["steps"])
    safety = x.get("safety") or (tiers[t]["text"] if t >= 2 else "")
    safety_html = f'<p class="xp-safety t{t}"><b>Safety</b>{escape(safety)}</p>' if safety else ""
    params = "".join(
        f'<label class="xp-param"><span>{sub(p["label"])}{(" (" + escape(p["unit"]) + ")") if p["unit"] else ""}</span>'
        f'<input type="number" step="any" inputmode="decimal" data-param="{p["id"]}" value="{p["value"]}"></label>'
        for p in x["params"])
    header = ",".join(c["id"] for c in x["cols"])
    cols = " · ".join(f'{sub(c["label"])}{(" (" + escape(c["unit"]) + ")") if c["unit"] else ""}' for c in x["cols"])
    results = "".join(f'<div data-key="{r["key"]}"><dt>{sub(r["label"])}</dt><dd>—</dd></div>' for r in x["results"])
    compare = "".join(f"<li>{sub(c['text'])} {chips(c['refs'], refs)}</li>" for c in x["compare"])
    leaves = "".join(f"<li>{sub(s)}</li>" for s in x["leaves_out"])
    real_btn = '<button type="button" class="btn primary" data-act="real">Use real data</button>' if x.get("real") else ""
    ex_btn = '<button type="button" class="btn" data-act="example">Load model data</button>' if x.get("example") else ""
    note = x["real"]["note"] if x.get("real") else (x["example"]["note"] if x.get("example") else "")
    return f"""  <article class="xp" id="ex-{x['id']}" data-tier="{t}" data-model="{x['model']}" aria-labelledby="ex-{x['id']}-h">
    <header class="xp-head">
      <p class="xp-meta"><span class="xp-code">EXPERIMENT {x['n']:02d}</span>{tier_badge(t)}<span class="xp-time">{escape(x['time'])}</span></p>
      <h2 id="ex-{x['id']}-h">{escape(x['title'])}</h2>
      <p class="xp-q">{sub(x['question'])}</p>
    </header>
    <div class="xp-grid">
      <div class="xp-method">
        <h3>How it maps to chip making</h3>
        <p>{sub(x['analog'])}</p>
        <ul class="xp-links">{links}</ul>
        <h3>You need</h3>
        <ul class="xp-need">{need}</ul>
        <h3>Method</h3>
        <ol class="xp-steps">{steps}</ol>
        {safety_html}
      </div>
      <div class="xp-fit card" data-model="{x['model']}" data-cols="{header}">
        <h3>Fit your data</h3>
        <p class="xp-small">One row per reading: {cols}. Paste from a spreadsheet, type, or open a CSV file.</p>
        <div class="xp-params">{params}</div>
        <label class="xp-label" for="csv-{x['id']}">Your readings (CSV)</label>
        <textarea id="csv-{x['id']}" class="xp-csv" rows="7" spellcheck="false" autocomplete="off">{header}\n</textarea>
        <div class="xp-actions">{real_btn}{ex_btn}<label class="btn xp-file">Open CSV<input type="file" accept=".csv,.txt,text/csv" data-act="file"></label><button type="button" class="btn" data-act="template">Download template</button></div>
        <p class="xp-note">{sub(note)}</p>
        <div class="xp-chart" role="img" aria-label="Straight-line fit for {escape(x['title'].lower())}: the points and the fitted line appear here once there are readings."></div>
        <dl class="xp-results">{results}<div data-key="r2"><dt>R² of the line</dt><dd>—</dd></div></dl>
        <p class="xp-status" aria-live="polite">Add at least three readings to fit a line.</p>
        <p class="xp-eq">{sub(FORMULA[x['model']])}</p>
      </div>
    </div>
    <div class="xp-after">
      <div><h3>Compare with</h3><ul class="xp-compare">{compare}</ul></div>
      <div><h3>What the model leaves out</h3><ul class="xp-leaves">{leaves}</ul></div>
    </div>
  </article>"""


def render(nav: str = NAV) -> str:
    exps = json.loads((DATA / "experiments.json").read_text(encoding="utf-8"))
    refs = {r["id"]: r for r in json.loads((DATA / "references.json").read_text(encoding="utf-8"))["references"]}
    xs, tiers = exps["experiments"], {t["tier"]: t for t in exps["tiers"]}
    used = sorted({k for x in xs for k in x["refs"]} | {k for x in xs for c in x["compare"] for k in c["refs"]},
                  key=lambda k: refs[k]["cite"])
    counts = {t: sum(1 for x in xs if x["tier"] == t) for t in tiers}
    filt = "".join(f'<button type="button" data-tier="{t}" aria-pressed="false">Tier {t} <span>{counts[t]}</span></button>' for t in sorted(tiers))
    tier_list = "".join(f'<li class="t{t["tier"]}"><b>{escape(t["name"])}</b><span>{escape(t["text"])}</span></li>' for t in exps["tiers"])
    src = "".join(f'<li id="ref-{k}">{escape(refs[k]["cite"])}'
                  + (f' <a href="https://doi.org/{escape(refs[k]["doi"])}" rel="noopener">doi</a>' if refs[k].get("doi") else
                     (f' <a href="{escape(refs[k]["url"])}" rel="noopener">link</a>' if refs[k].get("url") else ""))
                  + "</li>" for k in used)
    hero_pts = [(40, 168), (78, 150), (118, 128), (160, 112), (196, 90), (238, 70), (276, 54)]
    dots = "".join(f'<circle cx="{x}" cy="{y + (6 if i % 2 else -5)}" r="4.5" style="--i:{i}"/>' for i, (x, y) in enumerate(hero_pts))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Experiments · Transistor Foundry Expedition</title>
<meta name="description" content="Fourteen tiered experiments that make the physics of chip making measurable, from sand on a paper wafer to a diode thermometer, each with an in-browser CSV fit and cited comparisons.">
<link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="css/fonts.css">
<link rel="stylesheet" href="css/style.css">
<link rel="stylesheet" href="css/experiments.css">
<link rel="stylesheet" href="css/traveler.css">
<script>document.documentElement.classList.add('js')</script>
<!-- pwa:start · generated by scripts/build_pwa.py -->
<link rel="manifest" href="manifest.webmanifest">
<meta name="theme-color" content="#0a0d11">
<link rel="apple-touch-icon" href="assets/icons/icon-180.png">
<!-- pwa:end -->
</head>
<body class="xp-page">
<!-- generated by scripts/build_experiments.py from data/experiments.json; edit there -->
{nav}
<main>
<header class="xp-hero" id="top">
  <div class="wrap xp-hero-grid">
    <div>
      <p class="eyebrow">Experiments</p>
      <h1>{escape(exps['intro']['title'])}</h1>
      <p class="lead">{escape(exps['intro']['lead'])}</p>
      <div class="seg xp-filter" role="group" aria-label="Show experiments by safety tier"><button type="button" data-tier="all" aria-pressed="true">All <span>{len(xs)}</span></button>{filt}</div>
    </div>
    <svg class="xp-hero-fig" viewBox="0 0 320 220" role="img" aria-label="Readings scattered about a straight fitted line, with the residuals below">
      <line x1="24" y1="196" x2="300" y2="196" class="ax"/><line x1="24" y1="20" x2="24" y2="196" class="ax"/>
      <line x1="30" y1="178" x2="292" y2="42" class="fitline"/>{dots}
      <text x="296" y="214" text-anchor="end">x</text><text x="10" y="28">y</text>
    </svg>
  </div>
</header>
<section class="wrap sec xp-sec" id="bench" aria-labelledby="bench-h">
  <h2 id="bench-h">The bench</h2>
  <p class="xp-intro">Each experiment links to the process it stands in for. Pick one, take readings, and fit them below it. Nothing you type leaves your browser.</p>
  <ul class="xp-cards">
{chr(10).join(card(x) for x in xs)}
  </ul>
</section>
<section class="wrap sec xp-sec" id="xp-safety" aria-labelledby="xp-safety-h">
  <h2 id="xp-safety-h">Safety tiers</h2>
  <p class="xp-intro">The same tiers as the process manuals. Tiers 0 and 1 are for home or a classroom; tier 2 belongs in a supervised teaching lab; tier 3 is institution-only and shown here without any recipe.</p>
  <ul class="xp-tiers">{tier_list}</ul>
</section>
<section class="wrap xp-list" id="experiments" aria-label="Experiments">
{chr(10).join(article(x, refs, tiers) for x in xs)}
</section>
<section class="wrap sec xp-sec" id="xp-fitting" aria-labelledby="xp-fitting-h">
  <h2 id="xp-fitting-h">How the fits work</h2>
  <p class="xp-intro">Every experiment turns its readings into a straight line and fits it by ordinary least squares. The slope and intercept give the physics; their standard errors come from the scatter of the points about the line and are carried through to each result. “Load model data” fills the table with numbers made from the model itself, with a little noise added, and labels them as such: they are a way to try the fitter, not a measurement. The same code runs in Python (<code>sim/transistor_sim/physics/fitting.py</code>) and is checked against this page’s JavaScript by the tests.</p>
</section>
<section class="wrap sec xp-sec" id="xp-sources" aria-labelledby="xp-sources-h">
  <h2 id="xp-sources-h">Sources</h2>
  <ol class="xp-refs">{src}</ol>
</section>
</main>
<footer class="foot">
  <div class="wrap">
    <p>Transistor Foundry Expedition · Experiments. Code MIT, text and figures CC BY 4.0. Fits are straight lines through your own readings: check the residuals before you trust a number.</p>
    <p><a href="manuals.html">Process manuals →</a></p>
  </div>
</footer>
<script type="module" src="js/experiments/main.js"></script>
<script type="module" src="js/nav.js"></script>
<script type="module" src="js/traveler.js"></script>
</body>
</html>
"""


def main(argv):
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    m = re.search(r"<!-- nav:start.*?<!-- nav:end -->", old, re.S)     # keep the block build_nav.py wrote
    html = render(m.group(0) if m and 'class="nav-pages"' in m.group(0) else NAV)
    if "--check" in argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        # compare with the nav block stripped, since build_nav.py fills it afterwards
        strip = lambda s: re.sub(r"<!-- nav:start.*?<!-- nav:end -->", "", s, flags=re.S)
        return 0 if strip(cur) == strip(html) else 1
    OUT.write_text(html, encoding="utf-8")
    print(OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
